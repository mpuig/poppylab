/**
 * Emits `src/site/app-script.ts` from `src/site/app.js`, so the browser
 * script ships inside the server bundle on Node and on Workers alike.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import process from "node:process";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const source = path.join(root, "src/site/app.js");
export const target = path.join(root, "src/site/app-script.ts");
export const render = (js) =>
  `// Generated by scripts/site-script.mjs from src/site/app.js. Do not edit.\nexport const siteScript = ${JSON.stringify(js)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(target, render(readFileSync(source, "utf8")));
}
