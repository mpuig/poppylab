/**
 * Emits `src/site/app-script.ts` from `src/site/app.js`, so the browser
 * script ships inside the server bundle on Node and on Workers alike.
 *
 *   node scripts/site-script.mjs                    write it once
 *   node scripts/site-script.mjs --watch -- CMD…    write it, run CMD, and
 *                                                   write it again whenever
 *                                                   app.js changes until CMD
 *                                                   exits
 */
import { spawn } from "node:child_process";
import { existsSync, readFileSync, watchFile, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import process from "node:process";
import console from "node:console";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const source = path.join(root, "src/site/app.js");
export const target = path.join(root, "src/site/app-script.ts");
export const render = (js) =>
  `// Generated by scripts/site-script.mjs from src/site/app.js. Do not edit.\nexport const siteScript = ${JSON.stringify(js)};\n`;

// An unchanged file is left alone, so a watching dev server doesn't restart.
const write = () => {
  const next = render(readFileSync(source, "utf8"));
  if (!existsSync(target) || readFileSync(target, "utf8") !== next)
    writeFileSync(target, next);
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  write();
  const at = process.argv.indexOf("--");
  if (process.argv.includes("--watch") && at !== -1) {
    // Polling follows the path, so an editor that saves by replacing the
    // file is still seen.
    watchFile(source, { interval: 300 }, () => {
      try {
        write();
      } catch (error) {
        console.error(`site-script: ${error.message}`);
      }
    });
    const [command, ...args] = process.argv.slice(at + 1);
    const child = spawn(command, args, { stdio: "inherit" });
    for (const signal of ["SIGINT", "SIGTERM"])
      process.on(signal, () => child.kill(signal));
    child.on("exit", (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
  }
}
